import os
from dotenv import load_dotenv
from typing_extensions import TypedDict, NotRequired
from langchain_openai import AzureChatOpenAI
from langgraph.graph import StateGraph, START, END

load_dotenv()

AZURE_OPENAI_API_KEY = os.getenv("AZURE_OPENAI_API_KEY")
AZURE_OPENAI_API_VERSION = os.getenv("AZURE_OPENAI_API_VERSION")
AZURE_OPENAI_ENDPOINT = os.getenv("AZURE_OPENAI_ENDPOINT")
AZURE_OPENAI_CHAT_DEPLOYMENT_NAME = os.getenv("AZURE_OPENAI_CHAT_DEPLOYMENT_NAME")

required_settings = {
    "AZURE_OPENAI_API_KEY": AZURE_OPENAI_API_KEY,
    "AZURE_OPENAI_API_VERSION": AZURE_OPENAI_API_VERSION,
    "AZURE_OPENAI_ENDPOINT": AZURE_OPENAI_ENDPOINT,
    "AZURE_OPENAI_CHAT_DEPLOYMENT_NAME": AZURE_OPENAI_CHAT_DEPLOYMENT_NAME
}

missing_settings = [key for key, value in required_settings.items() if not value]

if missing_settings:
    raise ValueError(f"Missing required settings: {', '.join(missing_settings)}")

llm = AzureChatOpenAI(
    azure_endpoint=AZURE_OPENAI_ENDPOINT,
    api_key=AZURE_OPENAI_API_KEY,
    api_version=AZURE_OPENAI_API_VERSION,
    deployment_name=AZURE_OPENAI_CHAT_DEPLOYMENT_NAME
)

class State(TypedDict):
    topic: str

    # These fileds will be generated by nodes
    explanation: NotRequired[str]
    learning_material: NotRequired[str]

def generate_explanation(state: State):
    msg = llm.invoke(f"""
    Explain "{state['topic']}" to a beginner.

    Requirements:
    - Use simple language.
    - Keep it under 100 words.
    """)

    return {
        "explanation": msg.content
    }
def create_learning_material(state: State):
    msg = llm.invoke(f"""
    Based on the explanation below:

    1. Write three key points.
    2. Create one review question

    Topic:
    {state['topic']}

    Explanation:
    {state['explanation']}
    """)

    return {
        "learning_material": msg.content
    }

builder = StateGraph(State)

builder.add_node("generate_explanation", generate_explanation)
builder.add_node("create_learning_material", create_learning_material)

builder.add_edge(START,"generate_explanation")
builder.add_edge("generate_explanation", "create_learning_material")
builder.add_edge("create_learning_material", END)

app = builder.compile()

result = app.invoke({"topic": "Hybrid Search"})

print("\n================== Explanation ==================\n")
print(result["explanation"])

print("\n================== Learning Material ==================\n")
print(result["learning_material"])

print("\n================== Workflow ==================\n")
print(app.get_graph().draw_mermaid())